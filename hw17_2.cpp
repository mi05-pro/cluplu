#include <iostream>

class MyClass {
private:
    int value;                      // Звичайна змінна-член
    static int count;              // Статична змінна-член

public:
   
    MyClass(int val) : value(val) {
        count++;
        std::cout << "Конструктор: створено об'єкт зі значенням " << value
                  << ". Кількість об'єктів: " << count << std::endl;
    }

    ~MyClass() {
        std::cout << "Деструктор: видаляється об'єкт зі значенням " << value
                  << ". ";
        count--;
        std::cout << "Залишилось об'єктів: " << count << std::endl;
    }

    void showValue() const {
        std::cout << "Значення об'єкта: " << value << std::endl;
    }

    static void showCount() {
        std::cout << "Поточна кількість об'єктів: " << count << std::endl;
    }
};

// Ініціалізація статичної змінної
int MyClass::count = 0;

int main() {
    // Створення трьох об'єктів у динамічній пам'яті
    MyClass* obj1 = new MyClass(10);
    MyClass* obj2 = new MyClass(20);
    MyClass* obj3 = new MyClass(30);

    // Виведення значень кожного об'єкта
    obj1->showValue();
    obj2->showValue();
    obj3->showValue();

    // Виведення значення статичної змінної
    MyClass::showCount();

    // Послідовне видалення об'єктів
    delete obj1;
    MyClass::showCount();

    delete obj2;
    MyClass::showCount();

    delete obj3;
    
    return 0;
}

