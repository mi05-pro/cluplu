/* За оновленою умовою
Статична змінна-член count має бути приватною (private).
Доступ до неї — тільки через статичну функцію-член (наприклад, getCount() або showCount()).
*/

#include <iostream>

class MyClass {
private:
    int value;                       // Звичайна змінна-член
    static int count;               // Статична змінна-член (закрита)

public:
    MyClass(int val) : value(val) {
        count++;
        std::cout << "Конструктор: створено об'єкт зі значенням " << value << std::endl;
    }

    ~MyClass() {
        std::cout << "Деструктор: видаляється об'єкт зі значенням " << value << std::endl;
        count--;
    }

    void showValue() const {
        std::cout << "Значення об'єкта: " << value << std::endl;
    }

    // Статична функція-член для доступу до приватної змінної count
    static int getCount() {
        return count;
    }
};

// Ініціалізація статичної змінної
int MyClass::count = 0;

int main() {
    // Створення трьох об'єктів динамічно
    MyClass* obj1 = new MyClass(10);
    MyClass* obj2 = new MyClass(20);
    MyClass* obj3 = new MyClass(30);

    // Виведення значень об'єктів
    obj1->showValue();
    obj2->showValue();
    obj3->showValue();

    // Виведення значення статичної змінної через функцію-член
    std::cout << "Кількість об'єктів: " << MyClass::getCount() << std::endl;

    // Послідовне видалення об'єктів з виведенням кількості об'єктів
    delete obj1;
    std::cout << "Кількість об'єктів після видалення obj1: " << MyClass::getCount() << std::endl;

    delete obj2;
    std::cout << "Кількість об'єктів після видалення obj2: " << MyClass::getCount() << std::endl;

    delete obj3;
    std::cout << "Кількість об'єктів після видалення obj3: " << MyClass::getCount() << std::endl;

    return 0;
}

