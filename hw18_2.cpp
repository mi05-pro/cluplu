// опис класу BoundedArray (фіксований за розміром)
/*
Змінна-член: Масив з фіксованим розміром, переданим під час створення об'єкта.
Методи:
Конструктор для ініціалізації масиву з певним розміром.
Методи для доступу до елементів масиву (з перевіркою меж).
Метод для отримання розміру масиву.
Метод для виведення елементів масиву.
*/

#include <iostream>
#include <stdexcept> // Для виключень

class BoundedArray {
private:
    int* arr;           // Вказівник на масив
    /*
    size_t — це тип даних, який використовується 
    для представлення розмірів об'єктів або індексів масивів в C++ (і C)
    є беззнаковим (unsigned) типом, тобто він може зберігати тільки додатні числа (включаючи 0).
    Розмір залежить від архітектури:
    На 32-розрядних системах size_t зазвичай є 32-бітовим цілим числом (4 байти).
    На 64-розрядних системах size_t зазвичай є 64-бітовим цілим числом (8 байтів).
    */
    size_t size;        // Розмір масиву 

public:
    // Конструктор, ініціалізує масив заданого розміру
    BoundedArray(size_t s) : size(s) {
        arr = new int[size];  // Виділяємо пам'ять для масиву
    }

    // Деструктор для звільнення пам'яті
    ~BoundedArray() {
        delete[] arr;
    }

    // Метод для доступу до елементів масиву
    int& operator[](size_t index) {
        if (index >= size) {
            throw std::out_of_range("Індекс виходить за межі масиву");
        }
        return arr[index];
    }

    // Метод для отримання розміру масиву
    size_t getSize() const {
        return size;
    }

    // Метод для виведення всіх елементів масиву
    void display() const {
        for (size_t i = 0; i < size; ++i) {
            std::cout << arr[i] << " ";
        }
        std::cout << std::endl;
    }
};

int main() {
    try {
        BoundedArray arr(5);  // Створюємо масив з 5 елементів

        // Заповнюємо масив
        for (size_t i = 0; i < arr.getSize(); ++i) {
            arr[i] = static_cast<int>(i * 10); // Присвоюємо значення
        }

        /*
        static_cast — це один з операторів приведення типів в C++, 
        який дозволяє виконувати перетворення між типами на етапі компіляції. 
        Цей оператор застосовується для перетворення типів, коли ви впевнені, 
        що таке приведення є безпечним, 
        і що воно не призведе до помилок в час виконання програми
        
        */
        // Виводимо елементи масиву
        std::cout << "Масив: ";
        arr.display();

        // Тестуємо доступ за межами масиву (буде виключення)
        std::cout << arr[10] << std::endl;  // Виведе помилку

    } catch (const std::out_of_range& e) {
        std::cout << "Помилка: " << e.what() << std::endl;
    }

    return 0;
}
