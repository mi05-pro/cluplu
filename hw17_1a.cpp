/*
Уявімо, що ми створюємо програму, яка працює з користувачами. 
Ми хочемо знати, скільки користувачів створено на поточний момент (наприклад, одночасно залогінених).
*/


#include <iostream>
#include <string>

class User {
private:
    std::string username;
    static int userCount;  // Статична змінна: спільна для всіх об’єктів

public:
    User(std::string name) : username(name) {
        userCount++;
        std::cout << "Користувача '" << username << "' створено. "
                  << "Кількість користувачів: " << userCount << std::endl;
    }

    ~User() {
        userCount--;
        std::cout << "Користувача '" << username << "' видалено. "
                  << "Кількість користувачів: " << userCount << std::endl;
    }

    static int getUserCount() {
        return userCount;
    }
};

// Ініціалізація статичної змінної
int User::userCount = 0;

int main() {
    {
        User u1("Ivan");
        User u2("Oksana");
        User u3("Anna");
        User u4("Ruslan");

        std::cout << "Активних користувачів: " << User::getUserCount() << std::endl;
    } // Тут u1 і u2 знищуються — викликаються деструктори

    std::cout << "Після завершення блоку: Активних користувачів: " << User::getUserCount() << std::endl;

    return 0;
}

